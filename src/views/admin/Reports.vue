<script>
import { ref, computed, watch, onMounted } from 'vue';
import { SuccessToast, ErrorToast } from '@/functions/sweetalert';
import { generateReportApi, fetchReportsApi, fetchReportByIdApi, fetchAnalyticsReportApi } from '@/api';
import MonthPicker from '@/components/includes/MonthPicker.vue';

const PRESETS = {
  last12: 'Last 12 months',
  thisYear: 'This year',
  lastYear: 'Last year',
};

// Date -> "YYYY-MM"
const toMonthValue = (date) => `${date.getFullYear()}-${String(date.getMonth() + 1).padStart(2, '0')}`;

const presetRange = (key) => {
  const now = new Date();
  const year = now.getFullYear();
  if (key === 'thisYear') return { from: `${year}-01`, to: `${year}-12` };
  if (key === 'lastYear') return { from: `${year - 1}-01`, to: `${year - 1}-12` };
  return { from: toMonthValue(new Date(year, now.getMonth() - 11, 1)), to: toMonthValue(now) };
};

const MONTH_NAMES = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];

const REPORT_TYPES = {
  summary: 'System Summary',
  sales: 'Sales',
  orders: 'Orders',
  users: 'Users',
  stocks: 'Stocks',
};

// Flattens nested objects one level deep ({ Product: { name } } -> "Product.name")
const flattenRow = (row, prefix = '') =>
  Object.entries(row || {}).reduce((acc, [key, value]) => {
    const name = prefix ? `${prefix}.${key}` : key;
    if (value && typeof value === 'object' && !Array.isArray(value) && !prefix) {
      Object.assign(acc, flattenRow(value, name));
    } else {
      acc[name] = value && typeof value === 'object' ? JSON.stringify(value) : value;
    }
    return acc;
  }, {});

// A report's data holds one list (users, orders, stocks, payments) plus some
// totals; the list becomes the CSV rows. A summary report has no list, so
// its totals become "Metric, Value" rows instead.
const reportToCsv = (data) => {
  const parsed = typeof data === 'string' ? JSON.parse(data) : (data || {});
  // Orders reports also carry a short ordersByStatus list -- take the longest list
  const list = Object.values(parsed)
    .filter(Array.isArray)
    .reduce((longest, arr) => (arr.length > longest.length ? arr : longest), []);
  const rows = list.length
    ? list.map(item => flattenRow(item))
    : Object.entries(parsed).map(([Metric, Value]) => ({ Metric, Value }));

  const headers = [...new Set(rows.flatMap(Object.keys))];
  const escape = (v) => {
    const s = v === null || v === undefined ? '' : String(v);
    return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
  };
  return [headers.join(','), ...rows.map(r => headers.map(h => escape(r[h])).join(','))].join('\n');
};

export default {
  name: 'AdminReports',
  components: { MonthPicker },
  setup() {
    // Selected period as "YYYY-MM" months, both ends included
    const initialRange = presetRange('last12');
    const fromMonth = ref(initialRange.from);
    const toMonth = ref(initialRange.to);

    const activePreset = computed(() => Object.keys(PRESETS).find((key) => {
      const range = presetRange(key);
      return range.from === fromMonth.value && range.to === toMonth.value;
    }) || null);

    const applyPreset = (key) => {
      const range = presetRange(key);
      fromMonth.value = range.from;
      toMonth.value = range.to;
    };

    // e.g. "1 Nov 2025 – 31 Oct 2026"
    const rangeLabel = computed(() => {
      const [fromYear, fromMon] = fromMonth.value.split('-').map(Number);
      const [toYear, toMon] = toMonth.value.split('-').map(Number);
      const lastDay = new Date(toYear, toMon, 0).getDate();
      return `1 ${MONTH_NAMES[fromMon - 1]} ${fromYear} – ${lastDay} ${MONTH_NAMES[toMon - 1]} ${toYear}`;
    });

    const monthsLabel = computed(() => {
      const [fromYear, fromMon] = fromMonth.value.split('-').map(Number);
      const [toYear, toMon] = toMonth.value.split('-').map(Number);
      const months = (toYear - fromYear) * 12 + (toMon - fromMon) + 1;
      return months === 1 ? 'month' : `${months} months`;
    });

    // The cards and lists below come from /admin/analytics for the selected period (paid orders only).
    // Kept local so the Dashboard's all-time figures in the store are untouched.
    const metrics = ref({});
    const isLoading = ref(false);
    let latestRequest = 0; // ignore responses for a period the user has already moved away from
    const loadAnalytics = async () => {
      const requestId = ++latestRequest;
      isLoading.value = true;
      try {
        const res = await fetchAnalyticsReportApi({ from: fromMonth.value, to: toMonth.value });
        if (requestId === latestRequest) metrics.value = res.data;
      } catch (err) {
        if (requestId === latestRequest) ErrorToast('Could not load analytics', err.parsedMessage || err.message);
      } finally {
        if (requestId === latestRequest) isLoading.value = false;
      }
    };
    watch([fromMonth, toMonth], loadAnalytics);

    const money = (n) => Number(n || 0).toFixed(2);
    const pct = (part, whole) => (whole ? Math.round((part || 0) / whole * 1000) / 10 : 0);

    const topSelling = computed(() => (metrics.value.topSelling || []).slice(0, 5));

    const categoryShare = computed(() => {
      const entries = Object.entries(metrics.value.categoryRevenue || {});
      const total = entries.reduce((sum, [, revenue]) => sum + revenue, 0);
      return entries
        .map(([name, revenue]) => ({ name, revenue, percent: pct(revenue, total) }))
        .sort((a, b) => b.revenue - a.revenue);
    });

    const reportType = ref('summary');
    const savedReports = ref([]);
    const isGenerating = ref(false);

    const loadReports = async () => {
      try {
        const res = await fetchReportsApi();
        savedReports.value = res.data.reports || [];
      } catch (err) {
        ErrorToast('Could not load reports', err.parsedMessage || err.message);
      }
    };

    onMounted(() => {
      loadAnalytics();
      loadReports();
    });

    const generateReport = async () => {
      isGenerating.value = true;
      try {
        const res = await generateReportApi(reportType.value, { from: fromMonth.value, to: toMonth.value });
        SuccessToast('Report Saved', `${res.data.report.title} was generated and saved.`);
        await loadReports();
      } catch (err) {
        ErrorToast('Report Failed', err.parsedMessage || err.message);
      } finally {
        isGenerating.value = false;
      }
    };

    const downloadReport = async (report) => {
      try {
        const res = await fetchReportByIdApi(report.id);
        const csv = reportToCsv(res.data.report.data);
        // BOM so Excel opens UTF-8 (Khmer names etc.) correctly
        const blob = new Blob(['﻿' + csv], { type: 'text/csv;charset=utf-8' });
        const url = URL.createObjectURL(blob);
        const a = document.createElement('a');
        a.href = url;
        a.download = `MN-${report.reportType}-report-${report.id}.csv`;
        a.click();
        URL.revokeObjectURL(url);
      } catch (err) {
        ErrorToast('Download Failed', err.parsedMessage || err.message);
      }
    };

    return {
      PRESETS,
      fromMonth,
      toMonth,
      activePreset,
      applyPreset,
      rangeLabel,
      monthsLabel,
      isLoading,
      metrics,
      money,
      pct,
      topSelling,
      categoryShare,
      REPORT_TYPES,
      reportType,
      savedReports,
      isGenerating,
      generateReport,
      downloadReport
    };
  }
};
</script>
